"""Bundle an already-built normal ELF into the installer translation unit."""
from pathlib import Path
import sys

source, output = map(Path, sys.argv[1:])
data = source.read_bytes()
if len(data) < 64 or data[:4] != b'\x7fELF':
    raise SystemExit(f'Not an ELF payload: {source}')
output.parent.mkdir(parents=True, exist_ok=True)
with output.open('w', encoding='ascii', newline='\n') as stream:
    stream.write('/* Generated by tools/embed_payload.py. */\n#include "payload.h"\n\n')
    stream.write('const unsigned char xa_payload[] = {\n')
    for offset in range(0, len(data), 16):
        stream.write('  ' + ', '.join(f'0x{byte:02x}' for byte in data[offset:offset + 16]) + ',\n')
    stream.write('};\nconst size_t xa_payload_size = sizeof(xa_payload);\n')
